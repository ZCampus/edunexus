export type MessageKey = keyof typeof messages.sw;

type I18nContextValue = {
  locale: Locale;
  t: (key: MessageKey) => string;
  toggleLocale: () => void;
  setLocale: (locale: Locale) => void;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("sw");

  const t = useCallback(
    (key: MessageKey) => messages[locale][key],
    [locale],
  );

  const toggleLocale = useCallback(() => {
    setLocale((prev) => (prev === "sw" ? "en" : "sw"));
  }, []);

  const value = useMemo(
    () => ({ locale, t, toggleLocale, setLocale }),
    [locale, t, toggleLocale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return ctx;
}
